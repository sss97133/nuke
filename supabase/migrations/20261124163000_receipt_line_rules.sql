-- Receipt line classification as rows: receipt_line_labor_operation(text) and receipt_line_system(text) read
-- public.receipt_line_rules instead of a CASE of regular expressions typed into their bodies.
--
-- Why: the two bodies (migration 20261119200000) were 20 and 22 regex branches written in one parts vendor's
-- abbreviations for the 1973 proof car. A new car or vendor matched nothing and nothing counted it. Measured live
-- 2026-11-24 (receipt_items on live receipts, receipt_line_kind = 'part'): 441 part lines, 325 with a system, 49 with
-- a labor operation; on the vehicle-linked lines of every car but the proof car, 4 operations in 126 lines.
--
-- What this adds (revert: supabase/sql/revert_20261124163000_receipt_line_rules.sql):
--   receipt_line_systems                 the system keys a rule may assign (a row per key; adding a system is a row)
--   receipt_line_rules                   one row per pattern: classifier, priority (first match wins, unique among
--                                        active rules of a classifier), field, pattern, the key it assigns (operation_code
--                                        is an edge to labor_operations.code, system_key to receipt_line_systems),
--                                        optional scope (vendor pattern, make, years), status, source and proposer,
--                                        evidence item ids, promotion record
--   receipt_line_rule_hit(...)           the first active rule of a classifier that matches a line, with its rule_id;
--                                        scoped rules apply only when the caller passes the vendor/make/year they name
--   receipt_line_labor_operation(text)   same signature and output, now STABLE: the first active global rule
--   receipt_line_system(text)            same signature and output, now STABLE: the first active global rule
--
-- Exact reproduction: the 42 seed rows were generated by script from the live pg_get_functiondef output on 2026-11-24
-- (same pattern text, CASE position x 10 as priority), are all global, and keep the CASE order. Before the two
-- functions are replaced, the DO block below compares the legacy body against the rule reader over every
-- receipt_items description and every receipt_part_visible judgment description in production, and aborts the
-- migration on any difference. Patterns are matched against lower(text), as before.
-- Contract: supabase/sql/test_receipt_line_rules.sql.

