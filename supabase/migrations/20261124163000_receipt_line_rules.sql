$f$;
COMMENT ON FUNCTION public.receipt_line_labor_operation(text) IS
  'The labor_operations.code whose work fitting this part corresponds to, or null when no active global receipt_line_rules row matches. Rules are rows (receipt_line_rules, classifier labor_operation); the caller joins labor_operations for the hours; an unmatched part is a gap to count, never a default number.';

CREATE OR REPLACE FUNCTION public.receipt_line_system(p_text text)
RETURNS text LANGUAGE sql STABLE SET search_path = pg_catalog AS $f$
  SELECT h.output_key FROM public.receipt_line_rule_hit('system', p_text) h
$f$;
COMMENT ON FUNCTION public.receipt_line_system(text) IS
  'The receipt_line_systems key a receipt line names, read from its words by the first active global receipt_line_rules row (classifier system), or null. A reading of the paper, not proof the part was fitted.';

