CREATE TABLE public.receipt_line_rules (
  rule_id text PRIMARY KEY CHECK (rule_id ~ '^[a-z0-9][a-z0-9._-]*$'),
  classifier text NOT NULL CHECK (classifier IN ('labor_operation', 'system')),
  priority int NOT NULL CHECK (priority > 0),
  field text NOT NULL DEFAULT 'description' CHECK (field IN ('description', 'part_number')),
  pattern text NOT NULL CHECK (pattern <> ''),
  operation_code text REFERENCES public.labor_operations (code) ON UPDATE CASCADE,
  system_key text REFERENCES public.receipt_line_systems (system_key) ON UPDATE CASCADE,
  scope_vendor_pattern text,
  scope_make text,
  scope_year_min int,
  scope_year_max int,
  status text NOT NULL DEFAULT 'proposed' CHECK (status IN ('proposed', 'active', 'rejected', 'retired')),
  source text NOT NULL,
  proposed_by_agent_key text,
  proposed_by_user_id uuid,
  evidence_item_ids uuid[] NOT NULL DEFAULT '{}',
  supersedes_rule_id text REFERENCES public.receipt_line_rules (rule_id),
  promoted_at timestamptz,
  promotion_measure jsonb,
  retired_at timestamptz,
  note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT receipt_line_rules_output CHECK (
    (classifier = 'labor_operation' AND operation_code IS NOT NULL AND system_key IS NULL)
    OR (classifier = 'system' AND system_key IS NOT NULL AND operation_code IS NULL)),
  CONSTRAINT receipt_line_rules_years CHECK (scope_year_min IS NULL OR scope_year_max IS NULL OR scope_year_min <= scope_year_max),
  CONSTRAINT receipt_line_rules_proposer CHECK (proposed_by_agent_key IS NOT NULL OR proposed_by_user_id IS NOT NULL),
  CONSTRAINT receipt_line_rules_active_promoted CHECK (status <> 'active' OR promoted_at IS NOT NULL),
  CONSTRAINT receipt_line_rules_retired_at CHECK ((status = 'retired') = (retired_at IS NOT NULL))
);
CREATE UNIQUE INDEX receipt_line_rules_active_order ON public.receipt_line_rules (classifier, priority) WHERE status = 'active';
COMMENT ON TABLE public.receipt_line_rules IS
  'How a receipt line becomes a key (grain: one pattern). The first active rule of a classifier, by priority, whose pattern matches lower(field) and whose scope fits assigns operation_code (an edge to labor_operations) or system_key. Scope NULL = global; a scoped rule applies only through receipt_line_rule_hit with the vendor/make/year it names. Read by receipt_line_labor_operation(text), receipt_line_system(text) and receipt_line_rule_hit.';
COMMENT ON COLUMN public.receipt_line_rules.source IS 'Where the pattern came from (a document, a fold row, the legacy function body), in words a reviewer can check.';
COMMENT ON COLUMN public.receipt_line_rules.promotion_measure IS 'What was measured when the rule became active: lines compared, lines it fills, lines it changes.';

-- A pattern that does not compile never lands.
CREATE FUNCTION public.receipt_line_rules_check_pattern() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $f$
BEGIN
  PERFORM '' ~ NEW.pattern;
  IF NEW.scope_vendor_pattern IS NOT NULL THEN PERFORM '' ~ NEW.scope_vendor_pattern; END IF;
  RETURN NEW;
EXCEPTION WHEN invalid_regular_expression THEN
  RAISE EXCEPTION 'receipt_line_rules %: pattern does not compile (%)', NEW.rule_id, SQLERRM;
END $f$;
CREATE TRIGGER receipt_line_rules_check_pattern BEFORE INSERT OR UPDATE OF pattern, scope_vendor_pattern
  ON public.receipt_line_rules FOR EACH ROW EXECUTE FUNCTION public.receipt_line_rules_check_pattern();

