-- The first active rule of a classifier that matches. Rules are tried in priority order and the first hit returns, as
-- the CASE did. Scoped rules need the caller to pass what they name: with no vendor, a vendor-scoped rule never applies.
CREATE FUNCTION public.receipt_line_rule_hit(
  p_classifier text, p_text text, p_part_number text DEFAULT NULL,
  p_vendor text DEFAULT NULL, p_make text DEFAULT NULL, p_year int DEFAULT NULL)
RETURNS TABLE (rule_id text, output_key text)
LANGUAGE plpgsql STABLE SET search_path = pg_catalog AS $f$
DECLARE
  t text := lower(coalesce(p_text, ''));
  pn text := lower(coalesce(p_part_number, ''));
  v text := lower(p_vendor);
  r record;
BEGIN
  FOR r IN
    SELECT x.rule_id, x.field, x.pattern, coalesce(x.operation_code, x.system_key) AS k,
           x.scope_vendor_pattern, x.scope_make, x.scope_year_min, x.scope_year_max
      FROM public.receipt_line_rules x
     WHERE x.classifier = p_classifier AND x.status = 'active'
     ORDER BY x.priority, x.rule_id
  LOOP
    CONTINUE WHEN r.scope_vendor_pattern IS NOT NULL AND (v IS NULL OR NOT v ~ r.scope_vendor_pattern);
    CONTINUE WHEN r.scope_make IS NOT NULL AND (p_make IS NULL OR lower(p_make) <> lower(r.scope_make));
    CONTINUE WHEN r.scope_year_min IS NOT NULL AND (p_year IS NULL OR p_year < r.scope_year_min);
    CONTINUE WHEN r.scope_year_max IS NOT NULL AND (p_year IS NULL OR p_year > r.scope_year_max);
    IF (CASE r.field WHEN 'part_number' THEN pn ELSE t END) ~ r.pattern THEN
      rule_id := r.rule_id; output_key := r.k;
      RETURN NEXT;
      RETURN;
    END IF;
  END LOOP;
END $f$;
COMMENT ON FUNCTION public.receipt_line_rule_hit(text, text, text, text, text, int) IS
  'The first active receipt_line_rules row of a classifier (labor_operation | system) whose pattern matches lower(text) or lower(part_number) and whose scope fits the vendor/make/year passed, with its rule_id; no row when none matches.';

-- Proof before the swap: the legacy bodies (still installed) against the rule reader, over every receipt line text
-- production holds. Any difference aborts the migration.
DO $proof$
DECLARE
  n_texts int;
  n_diff int;
BEGIN
  WITH texts AS (
    SELECT DISTINCT i.description AS t FROM public.receipt_items i
    UNION
    SELECT DISTINCT coalesce(e.params->>'description', e.params#>>'{question_context,description}', '')
      FROM public.evidence_judgment_requests e
     WHERE e.question_kind = 'receipt_part_visible'
  )
  SELECT count(*),
         count(*) FILTER (WHERE public.receipt_line_system(t)
                                  IS DISTINCT FROM (SELECT h.output_key FROM public.receipt_line_rule_hit('system', t) h)
                             OR public.receipt_line_labor_operation(t)
                                  IS DISTINCT FROM (SELECT h.output_key FROM public.receipt_line_rule_hit('labor_operation', t) h))
    INTO n_texts, n_diff
    FROM texts;
  IF n_diff > 0 THEN
    RAISE EXCEPTION 'receipt_line_rules does not reproduce the legacy classifiers: % of % line texts differ', n_diff, n_texts;
  END IF;
  UPDATE public.receipt_line_rules
     SET promotion_measure = jsonb_build_object('basis', 'legacy_reproduction', 'texts_compared', n_texts,
                                                'texts_changed', 0, 'measured_at', now());
  RAISE NOTICE 'receipt_line_rules reproduces the legacy classifiers on % distinct line texts', n_texts;
END $proof$;

CREATE OR REPLACE FUNCTION public.receipt_line_labor_operation(p_text text)
RETURNS text LANGUAGE sql STABLE SET search_path = pg_catalog AS $f$
