"""Write the seed migration for public.vehicle_decode_rules from build_gm_rules.py output.

Usage: python3 -I emit_migration.py <rules.json> <migration.sql>

GM-wide rows (Muncie, Saginaw) carry make NULL so a reader that narrows by the vehicle's make still
finds them; qualifiers.oem_group names the scope. The insert skips a row whose current-row key
(rule_key, make, model, code, year range, citation_url) already exists, so a replay adds nothing; a
corrected reading supersedes, never updates.
"""
import json
import sys

rows = json.load(open(sys.argv[1]))
out = []
for r in rows:
    v = dict(r["value"])
    q = dict(r.get("qualifiers") or {})
    make = r["make"]
    if make == "GM":
        make = None
        q["oem_group"] = "GM"
    out.append({
        "rule_key": r["rule_key"], "make": make, "model": r["model"], "code": r["code"],
        "year_min": r["year_min"], "year_max": r["year_max"], "value": v, "qualifiers": q,
        "citation_url": r["citation_url"], "citation_title": r["citation_title"],
        "citation_locator": r["citation_locator"], "cited_on": r["cited_on"],
    })

payload = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
tag = "decode_rules_gm_seed"
assert f"${tag}$" not in payload

from collections import Counter
counts = Counter((r["rule_key"]) for r in out)
by_src = Counter(r["citation_url"].split("/")[2] for r in out)

sql = f"""-- Seed public.vehicle_decode_rules (created empty by 20261116016000_vehicle_facet_items) with cited GM and
-- Pontiac decode charts. Chart decodes only: no vehicle observation is written. Generated by
-- scripts/decode-rules/build_gm_rules.py + emit_migration.py from saved chart copies; one chart_source row per
-- document names the copy (sha256) its rows came from. HPP rows are a hand transcription of the scanned pages
-- (scripts/decode-rules/hpp_1973_firebird.json).
--
-- Rows: {len(out)}. By source: {', '.join(f'{k} {n}' for k, n in sorted(by_src.items()))}.
-- By rule_key: {', '.join(f'{k} {n}' for k, n in sorted(counts.items()))}.
--
-- Charts that disagree stay as separate rows (qualifiers.conflicts_with). GM-wide rows have make NULL and
-- qualifiers.oem_group = 'GM'. Codes already held by paint_codes, vintage_rpo_codes or gm_rpo_library are
-- referenced (value.ref / qualifiers.also_in), not copied. A replay inserts nothing.

SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '10s';

INSERT INTO public.vehicle_decode_rules
  (rule_key, make, model, code, year_min, year_max, value, qualifiers, citation_url, citation_title, citation_locator, cited_on)
SELECT s.rule_key, s.make, s.model, s.code, s.year_min, s.year_max, s.value, s.qualifiers, s.citation_url, s.citation_title,
       s.citation_locator, s.cited_on
FROM jsonb_to_recordset(${tag}${payload}${tag}$::jsonb) AS s(
  rule_key text, make text, model text, code text, year_min integer, year_max integer, value jsonb, qualifiers jsonb,
  citation_url text, citation_title text, citation_locator text, cited_on date)
WHERE NOT EXISTS (
  SELECT 1 FROM public.vehicle_decode_rules e
  WHERE e.rule_key = s.rule_key AND e.make IS NOT DISTINCT FROM s.make AND e.model IS NOT DISTINCT FROM s.model
    AND e.code IS NOT DISTINCT FROM s.code AND e.year_min IS NOT DISTINCT FROM s.year_min
    AND e.year_max IS NOT DISTINCT FROM s.year_max AND e.citation_url = s.citation_url AND e.superseded_at IS NULL);

DO $check$
DECLARE n integer;
BEGIN
  SELECT count(*) INTO n FROM public.vehicle_decode_rules WHERE superseded_at IS NULL
    AND citation_url IN ('https://www.randysworldwide.com/import_export/Muncie_Trans_ID.pdf',
                         'https://www.thepartsplaceinc.com/data-sheets/PontiacEngineCodes.pdf');
  IF n < {sum(1 for r in out if r['citation_url'] in ('https://www.randysworldwide.com/import_export/Muncie_Trans_ID.pdf', 'https://www.thepartsplaceinc.com/data-sheets/PontiacEngineCodes.pdf'))} THEN
    RAISE EXCEPTION 'decode rule seed incomplete: % RANDYS + Parts Place rows', n;
  END IF;
END
$check$;
"""
open(sys.argv[2], "w").write(sql)
print(len(out), "rows,", len(sql) // 1024, "KiB")
